"""Exploratory analysis: writes reports/data_profile.md and figures. Run: python -m creditrisk.eda"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from . import config as C  # noqa: E402
from .data import load_raw  # noqa: E402


def _rate_plot(series: pd.Series, y: pd.Series, title: str, xlabel: str, path) -> None:
    rate = y.groupby(series, observed=True).mean() * 100
    fig, ax = plt.subplots(figsize=(6.5, 4))
    rate.plot.bar(ax=ax, color="#0B3C5D")
    ax.set(title=title, xlabel=xlabel, ylabel="Default rate (%)")
    ax.axhline(y.mean() * 100, color="#D9534F", ls="--", label=f"Overall {y.mean():.1%}")
    ax.legend(); plt.setp(ax.get_xticklabels(), rotation=0)
    fig.tight_layout(); fig.savefig(path, dpi=140); plt.close(fig)


def main() -> None:
    df = load_raw()
    y = df[C.TARGET]
    C.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    miss_income = df["MonthlyIncome"].isna()
    sentinel = df[C.PAST_DUE_COLS].isin(C.PAST_DUE_SENTINELS).any(axis=1)

    _rate_plot(df["NumberOfTimes90DaysLate"].clip(upper=5).astype(str).replace("5", "5+"), y,
               "Default rate by number of 90+ day lates", "Times 90+ days late", C.FIGURES_DIR / "eda_90day_late.png")
    age_band = pd.cut(df["age"], [17, 30, 40, 50, 60, 70, 120], labels=["<=30", "31-40", "41-50", "51-60", "61-70", "70+"])
    _rate_plot(age_band, y, "Default rate by age band", "Age band", C.FIGURES_DIR / "eda_age.png")
    util_band = pd.cut(df["RevolvingUtilizationOfUnsecuredLines"], [-0.01, 0.1, 0.3, 0.6, 1.0, 1e9],
                       labels=["<=10%", "10-30%", "30-60%", "60-100%", ">100%"])
    _rate_plot(util_band, y, "Default rate by credit utilisation", "Utilisation of credit limits", C.FIGURES_DIR / "eda_utilisation.png")

    lines = [
        "# Data profile (generated by `python -m creditrisk.eda`)\n",
        f"- Rows: **{len(df):,}**, features: {len(C.RAW_FEATURES)}, default rate: **{y.mean():.2%}**",
        f"- Missing MonthlyIncome: **{miss_income.mean():.1%}** ({int(miss_income.sum()):,} rows); "
        f"missing NumberOfDependents: {df['NumberOfDependents'].isna().mean():.1%}",
        f"- Past-due special codes (96/98) in {int(sentinel.sum())} rows, whose default rate is **{y[sentinel].mean():.1%}**",
        f"- Age below 18: {int((df['age'] < 18).sum())} row(s); utilisation above 100%: {int((df['RevolvingUtilizationOfUnsecuredLines'] > 1).sum()):,} rows",
        f"- Median DebtRatio when income is present: {df.loc[~miss_income, 'DebtRatio'].median():.2f}; "
        f"when income is missing: {df.loc[miss_income, 'DebtRatio'].median():,.0f} (the field then holds a large absolute figure, not a ratio)",
        f"- Default rate with income missing: {y[miss_income].mean():.2%} vs present: {y[~miss_income].mean():.2%}",
        "",
        "## Default rate by 90+ day lates",
        df.groupby(df["NumberOfTimes90DaysLate"].clip(upper=5))[C.TARGET].agg(["size", "mean"]).rename(
            columns={"size": "borrowers", "mean": "default_rate"}).round(3).to_markdown(),
    ]
    (C.REPORTS_DIR / "data_profile.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote reports/data_profile.md and EDA figures")


if __name__ == "__main__":
    main()
